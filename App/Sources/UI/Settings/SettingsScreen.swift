/// A slider drawn with the theme's neutral greys (the system track is blue-tinted).
///
/// Only the thumb is draggable and the track reacts to taps, so a vertical swipe that starts
/// on the row still scrolls the form. Supports VoiceOver adjust actions and reports editing
/// begin/end like `Slider`.
struct NeutralSlider: View {
    @Binding var value: Double
    let range: ClosedRange<Double>
    let step: Double
    var onEditingChanged: (Bool) -> Void = { _ in }

    @State private var isEditing = false
    private let thumb: CGFloat = 26

    var body: some View {
        GeometryReader { proxy in
            let width = max(proxy.size.width - thumb, 1)
            let fraction = (value - range.lowerBound) / (range.upperBound - range.lowerBound)
            ZStack(alignment: .leading) {
                Capsule().fill(Theme.textTertiary.opacity(0.35)).frame(height: 5)
                Capsule().fill(Theme.textPrimary).frame(width: thumb / 2 + width * fraction, height: 5)
                Circle()
                    .fill(Color.white)
                    .shadow(color: .black.opacity(0.25), radius: 3, y: 1)
                    .overlay(Circle().strokeBorder(Theme.hairline))
                    .frame(width: thumb, height: thumb)
                    // 44 pt hit area around the 26 pt thumb.
                    .frame(width: 44, height: 44)
                    .contentShape(Rectangle())
                    .offset(x: width * fraction - (44 - thumb) / 2)
                    .gesture(
                        DragGesture(minimumDistance: 0, coordinateSpace: .named("track"))
                            .onChanged { gesture in
                                if !isEditing {
                                    isEditing = true
                                    onEditingChanged(true)
                                }
                                set(position: gesture.location.x, width: width)
                            }
                            .onEnded { _ in
                                isEditing = false
                                onEditingChanged(false)
                            })
            }
            .frame(maxHeight: .infinity)
            .contentShape(Rectangle())
            .coordinateSpace(.named("track"))
            .onTapGesture(coordinateSpace: .local) { location in
                set(position: location.x, width: width)
                onEditingChanged(false)
            }
        }
        .frame(height: 44)
        .accessibilityElement()
        .accessibilityAdjustableAction { direction in
            switch direction {
            case .increment: set(value + step)
            case .decrement: set(value - step)
            @unknown default: break
            }
            onEditingChanged(false)
        }
    }

    private func set(position x: CGFloat, width: CGFloat) {
        let raw = (x - thumb / 2) / width
        set(range.lowerBound + Double(min(max(raw, 0), 1)) * (range.upperBound - range.lowerBound))
    }

    private func set(_ newValue: Double) {
        let stepped = (newValue / step).rounded() * step
        let clamped = min(max(stepped, range.lowerBound), range.upperBound)
        if clamped != value { value = clamped }
    }
}
