/// Generation settings, privacy and legal information, and device details.
struct SettingsScreen: View {
    let environment: AppEnvironment
    @Environment(\.dismiss) private var dismiss

    private var chat: ChatViewModel { environment.chat }

    /// DEBUG demo scene `about` opens the sheet scrolled to the About and Device sections.
    private var startsAtBottom: Bool {
        #if DEBUG
            return environment.demoScene == .about
        #else
            return false
        #endif
    }

    var body: some View {
        NavigationStack {
            ScrollViewReader { proxy in
                Form {
                    GenerationSection(chat: chat)
                    privacySection
                    aboutSection
                    DeviceSection(environment: environment)
                }
                .task {
                    guard startsAtBottom else { return }
                    try? await Task.sleep(for: .milliseconds(300))
                    proxy.scrollTo(DeviceSection.lastRowID, anchor: .bottom)
                }
            }
            .scrollContentBackground(.hidden)
            .background(Theme.groupedBackground)
            .navigationTitle(Text("Settings"))
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .confirmationAction) {
                    Button("Done") { dismiss() }
                }
            }
        }
    }

    private var privacySection: some View {
        Section {
            VStack(alignment: .leading, spacing: 10) {
                Label {
                    Text("Runs on this iPhone")
                        .font(.body.weight(.semibold))
                        .foregroundStyle(Theme.textPrimary)
                } icon: {
                    Image(systemName: "lock").foregroundStyle(Theme.textSecondary)
                }
                Text(
                    "Models run entirely on this device. There are no accounts, no analytics and no data collection, and nothing you type is sent to a server. Your conversation is stored only on this iPhone (and, like other app data, in your own iCloud or computer backup). The only network use is downloading model files from huggingface.co when you ask for it."
                )
                .font(.subheadline)
                .foregroundStyle(Theme.textSecondary)
                .fixedSize(horizontal: false, vertical: true)
            }
            .padding(.vertical, 6)
            .listRowBackground(Theme.groupedRow)

            VStack(alignment: .leading, spacing: 8) {
                Label {
                    Text("AI-generated content")
                        .font(.body.weight(.semibold))
                        .foregroundStyle(Theme.textPrimary)
                } icon: {
                    Image(systemName: "exclamationmark.bubble").foregroundStyle(Theme.textSecondary)
                }
                Text(
                    "Replies are generated by a small language model and may be inaccurate or inappropriate. Check anything important."
                )
                .font(.subheadline)
                .foregroundStyle(Theme.textSecondary)
                .fixedSize(horizontal: false, vertical: true)
            }
            .padding(.vertical, 6)
            .listRowBackground(Theme.groupedRow)
        } header: {
            SectionHeader("Privacy")
        }
    }

    private var aboutSection: some View {
        Section {
            InfoRow(title: Text("Version"), value: "\(AppLinks.version) (\(AppLinks.build))", monospaced: true)
            NavigationLink {
                AcknowledgementsView()
            } label: {
                RowLabel(title: Text("Acknowledgements"), systemImage: "doc.text")
            }
            .listRowBackground(Theme.groupedRow)
            NavigationLink {
                ModelLicensesView(catalog: environment.store.catalog)
            } label: {
                RowLabel(title: Text("Model licenses"), systemImage: "checkmark.seal")
            }
            .listRowBackground(Theme.groupedRow)
            if let url = AppLinks.privacyPolicy {
                LinkRow(title: Text("Privacy Policy"), systemImage: "hand.raised", url: url)
            }
            if let url = AppLinks.support {
                LinkRow(title: Text("Support"), systemImage: "questionmark.circle", url: url)
                LinkRow(
                    title: Text("Report a problematic response"),
                    systemImage: "exclamationmark.bubble", url: url)
            }
        } header: {
            SectionHeader("About")
        }
    }
}

// MARK: - Generation

private struct GenerationSection: View {
    let chat: ChatViewModel

    @State private var systemPrompt = ""
    @State private var temperature: Double = 0.7
    @State private var temperatureIsDefault = true
    @FocusState private var promptFocused: Bool

    private static let maxTokenChoices = [256, 512, 1024, 2048, 4096]

    private var defaults: SamplingDefaults? {
        chat.currentModel?.recommendedSampling(thinking: chat.settings.thinkingEnabled)
    }

    var body: some View {
        Section {
            VStack(alignment: .leading, spacing: 8) {
                Text("System prompt")
                    .font(.subheadline.weight(.medium))
                    .foregroundStyle(Theme.textPrimary)
                TextField(
                    text: $systemPrompt,
                    prompt: Text("e.g. Answer briefly. Use metric units.").foregroundStyle(Theme.textTertiary),
                    axis: .vertical
                ) {
                    Text("System prompt")
                }
                .font(.body)
                .foregroundStyle(Theme.textPrimary)
                .lineLimit(3...8)
                .focused($promptFocused)
                .onChange(of: promptFocused) { _, focused in
                    if !focused { commitSystemPrompt() }
                }
            }
            .padding(.vertical, 6)
            .listRowBackground(Theme.groupedRow)

            VStack(alignment: .leading, spacing: 6) {
                HStack {
                    Text("Temperature")
                        .font(.subheadline.weight(.medium))
                        .foregroundStyle(Theme.textPrimary)
                    Spacer()
                    Text(verbatim: shownTemperature.formatted(.number.precision(.fractionLength(2))))
                        .font(.mono(.subheadline, weight: .medium))
                        .foregroundStyle(Theme.textPrimary)
                    if temperatureIsDefault {
                        Text("default")
                            .font(.caption)
                            .foregroundStyle(Theme.textTertiary)
                    }
                }
                NeutralSlider(value: temperatureBinding, range: 0...1.5, step: 0.05) { editing in
                    if !editing {
                        temperatureIsDefault = false
                        chat.settings.temperature = Float(temperature)
                    }
                }
                .accessibilityLabel(Text("Temperature"))
                .accessibilityValue(Text(verbatim: shownTemperature.formatted(.number.precision(.fractionLength(2)))))
                HStack {
                    Text("Precise")
                    Spacer()
                    Text("Creative")
                }
                .font(.caption)
                .foregroundStyle(Theme.textTertiary)
            }
            .padding(.vertical, 6)
            .listRowBackground(Theme.groupedRow)

            Picker(selection: maxTokensBinding) {
                Text(defaultTokensTitle).tag(0)
                ForEach(Self.maxTokenChoices, id: \.self) { value in
                    Text(verbatim: "\(value)").tag(value)
                }
            } label: {
                Text("Max response tokens")
                    .font(.subheadline.weight(.medium))
                    .foregroundStyle(Theme.textPrimary)
            }
            .pickerStyle(.menu)
            .listRowBackground(Theme.groupedRow)

            Button {
                chat.settings.temperature = nil
                chat.settings.topP = nil
                chat.settings.maxTokens = nil
                loadDraft()
            } label: {
                Text("Reset to model defaults")
                    .font(.subheadline.weight(.medium))
            }
            .disabled(chat.settings.temperature == nil && chat.settings.maxTokens == nil && chat.settings.topP == nil)
            .listRowBackground(Theme.groupedRow)
        } header: {
            SectionHeader("Generation")
        } footer: {
            SectionFooter(
                "Changes apply to the next reply. Defaults come from each model's recommended settings; longer replies use more memory.")
        }
        .onAppear(perform: loadDraft)
        .onDisappear(perform: commitSystemPrompt)
    }

    private var defaultTokensTitle: String {
        if let defaults {
            return String(localized: "Default (\(String(defaults.maxTokens)))")
        }
        return String(localized: "Default")
    }

    /// While the default applies, show the current model's value (it depends on thinking).
    private var shownTemperature: Double {
        temperatureIsDefault ? Double(defaults?.temperature ?? 0.7) : temperature
    }

    private var temperatureBinding: Binding<Double> {
        Binding(
            get: { shownTemperature },
            set: {
                temperature = $0
                temperatureIsDefault = false
            })
    }

    private var maxTokensBinding: Binding<Int> {
        Binding(
            get: { chat.settings.maxTokens ?? 0 },
            set: { chat.settings.maxTokens = $0 == 0 ? nil : $0 })
    }

    private func loadDraft() {
        systemPrompt = chat.settings.systemPrompt
        if let value = chat.settings.temperature {
            temperature = Double(value)
            temperatureIsDefault = false
        } else {
            temperature = Double(defaults?.temperature ?? 0.7)
            temperatureIsDefault = true
        }
    }

    private func commitSystemPrompt() {
        if chat.settings.systemPrompt != systemPrompt {
            chat.settings.systemPrompt = systemPrompt
        }
    }
}

// MARK: - Device

private struct DeviceSection: View {
    let environment: AppEnvironment
    static let lastRowID = "device-engine"

    @State private var snapshot: MemorySnapshot?
    @State private var entitlements: EntitlementReport?

    var body: some View {
        let snapshot = self.snapshot ?? environment.chat.capability.snapshot()
        let entitlements = self.entitlements ?? EntitlementReport.current()
        Section {
            InfoRow(title: Text("Hardware model"), value: Self.deviceIdentifier(), monospaced: !isSimulator)
            InfoRow(
                title: Text("Physical memory"), value: Format.memory(snapshot.physicalMemoryBytes),
                monospaced: true)
            if let limit = snapshot.processLimitBytes {
                InfoRow(title: Text("Memory limit for this app"), value: Format.memory(limit), monospaced: true)
            } else {
                InfoRow(title: Text("Memory limit for this app"), value: String(localized: "Not reported"))
            }
            InfoRow(
                title: Text("Memory in use"), value: Format.memory(snapshot.footprintBytes), monospaced: true)
            InfoRow(title: Text("Increased memory limit"), value: entitlementStatus(entitlements))
            InfoRow(title: Text("Thermal state"), value: environment.safety.thermalLevel.localizedName)
            InfoRow(
                title: Text("Engine"),
                value: environment.usesMockBackend
                    ? String(localized: "Simulated (no GPU)") : String(localized: "MLX on the GPU"))
                .id(Self.lastRowID)
        } header: {
            SectionHeader("Device")
                // Memory numbers change while a model loads or generates: refresh every 2 s.
                .task {
                    self.entitlements = EntitlementReport.current()
                    while !Task.isCancelled {
                        self.snapshot = environment.chat.capability.snapshot()
                        try? await Task.sleep(for: .seconds(2))
                    }
                }
        } footer: {
            SectionFooter(
                "The memory limit decides which models can load. The increased-memory entitlement raises it on supported iPhones.")
        }
    }

    private var isSimulator: Bool {
        #if targetEnvironment(simulator)
            true
        #else
            false
        #endif
    }

    private func entitlementStatus(_ report: EntitlementReport) -> String {
        if report.increasedMemoryLimitLikelyEffective { return String(localized: "Active") }
        if report.increasedMemoryLimitSigned == true { return String(localized: "Not granted") }
        return String(localized: "Not signed")
    }

    private static func deviceIdentifier() -> String {
        #if targetEnvironment(simulator)
            return String(localized: "Simulator")
        #else
            var info = utsname()
            uname(&info)
            return withUnsafeBytes(of: info.machine) { raw in
                String(decoding: raw.prefix(while: { $0 != 0 }), as: UTF8.self)
            }
        #endif
    }
}

