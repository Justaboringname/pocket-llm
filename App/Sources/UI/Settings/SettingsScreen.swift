struct InfoRow: View {
    let title: Text
    let value: String
    /// Monospaced for numbers only (CJK text in a monospaced font gets odd spacing).
    var monospaced = false

    var body: some View {
        HStack(alignment: .firstTextBaseline, spacing: 12) {
            title
                .font(.subheadline)
                .foregroundStyle(Theme.textPrimary)
            Spacer(minLength: 8)
            Text(verbatim: value)
                .font(monospaced ? .mono(.subheadline) : .subheadline)
                .foregroundStyle(Theme.textSecondary)
                .multilineTextAlignment(.trailing)
        }
        .accessibilityElement(children: .combine)
        .listRowBackground(Theme.groupedRow)
    }
}

